from train import run_training, split_holdout_test

logging.basicConfig(level=logging.INFO, format="%(asctime)s [%(levelname)s] %(message)s")
logger = logging.getLogger("EnviroTrust.SyntheticGenerator")

# Standard measurement units and features
# Latest 15% of normal_demo.csv is held out: never used for fitting or threshold calibration
DEMO_TEST_RATIO = 0.15

SIMULATION_FEATURES = [
    "COD_mg_L",
    "BOD_mg_L",
    "pH",
    "TDS_mg_L",
    "turbidity_NTU",
    "colour_PtCo",
    "total_solids_mg_L",
    "total_suspended_solids_mg_L",
    "chloride_mg_L",
    "sulphate_mg_L",
]


def generate_synthetic_dataset(
    n_normal: int = 1000,
    n_attack: int = 200,
    random_seed: int = 42,
    start_time: Optional[datetime] = None,
) -> Tuple[pd.DataFrame, pd.DataFrame]:
    """
    Generate synthetic normal wastewater telemetry and distinct attack scenarios.

    Parameters:
        n_normal: Approximate number of normal operating observations (~1,000).
        n_attack: Approximate number of labeled attack observations (~200).
        random_seed: Seed for reproducible pseudorandom generation.
        start_time: Starting UTC datetime for time-series timestamps.

    Returns:
        Tuple of (df_normal, df_attack)
    """
    rng = np.random.RandomState(random_seed)
    base_time = start_time or datetime(2026, 11, 1, 8, 0, 0, tzinfo=timezone.utc)

    # ==========================================================================
    # 1. NORMAL OPERATING BASELINE GENERATION
    # ==========================================================================
    normal_records: List[Dict[str, Any]] = []

    for i in range(n_normal):
        t_stamp = base_time + timedelta(minutes=10 * i)
        hour_frac = (t_stamp.hour + t_stamp.minute / 60.0)
        diurnal_factor = np.sin(2.0 * np.pi * hour_frac / 24.0)

        # Baseline COD with diurnal operational cycle and noise
        # Literature baseline for raw dye effluent: 4500 - 8500 mg/L
        cod_mean = 5800.0 + 400.0 * diurnal_factor
        cod = float(rng.normal(cod_mean, 650.0))
        cod = max(3800.0, min(9200.0, cod))

        # Biodegradability correlation (BOD = 0.21 - 0.28 * COD)
        bod_ratio = rng.uniform(0.22, 0.27)
        bod = float(cod * bod_ratio + rng.normal(0, 30.0))
        bod = max(800.0, min(2400.0, bod))

        # pH buffered near neutral/weakly alkaline dye wash: 6.2 - 7.6
        ph = float(rng.normal(6.85, 0.30))
        ph = max(6.0, min(7.7, ph))

        # Suspended Solids (TSS)
        tss = float(rng.normal(380.0 + 40.0 * diurnal_factor, 75.0))
        tss = max(130.0, min(650.0, tss))

        # Turbidity physically coupled to TSS
        turbidity = float(0.85 * tss + rng.normal(0, 25.0))
        turbidity = max(120.0, min(620.0, turbidity))

        # Dissolved Solids (TDS)
        tds = float(rng.normal(2850.0 + 100.0 * diurnal_factor, 260.0))
        tds = max(2200.0, min(3700.0, tds))

        # Mass conservation: Total Solids = TDS + TSS + gravimetric analytical error
        gravimetric_err = float(rng.normal(0, 18.0))
        ts = float(tds + tss + gravimetric_err)

        # Colour correlated with COD and turbidity
        colour = float(0.38 * cod + 1.8 * turbidity + rng.normal(0, 120.0))
        colour = max(1000.0, min(4200.0, colour))

        # Ionic constituents (bounded within TDS)
        chloride = float(0.12 * tds + rng.normal(0, 25.0))
        chloride = max(260.0, min(520.0, chloride))

        sulphate = float(0.15 * tds + rng.normal(0, 35.0))
        sulphate = max(270.0, min(640.0, sulphate))

        normal_records.append({
            "sample_id": f"SYNTH_NORM_{i+1:05d}",
            "timestamp": t_stamp.isoformat(),
            "COD_mg_L": round(cod, 2),
            "BOD_mg_L": round(bod, 2),
            "pH": round(ph, 2),
            "TDS_mg_L": round(tds, 2),
            "turbidity_NTU": round(turbidity, 2),
            "colour_PtCo": round(colour, 2),
            "total_solids_mg_L": round(ts, 2),
            "total_suspended_solids_mg_L": round(tss, 2),
            "chloride_mg_L": round(chloride, 2),
            "sulphate_mg_L": round(sulphate, 2),
            "is_anomaly": 0,
            "label": "normal",
            "attack_type": "none",
            "data_provenance": "SYNTHETIC",
            "is_synthetic": True,
        })

    df_normal = pd.DataFrame(normal_records)

    # ==========================================================================
    # 2. SEPARATELY LABELLED ATTACK SCENARIOS
    # ==========================================================================
    attack_records: List[Dict[str, Any]] = []
    atk_time_start = base_time + timedelta(minutes=10 * n_normal + 60)

    # Partition n_attack across the 6 scenarios
    scenario_counts = {
        "low_cod": max(20, n_attack // 6),
        "high_cod": max(20, n_attack // 6),
        "cod_turbidity_decoupling": max(20, n_attack // 6),
        "sensor_flatline": max(20, n_attack // 6),
        "sudden_spike": max(20, n_attack // 6),
        "gradual_drift": max(20, n_attack - 5 * (n_attack // 6)),
    }

    curr_time = atk_time_start
    atk_counter = 0

    # Helper: default normal base reading to modify for attacks
    def make_base_effluent(t: datetime) -> Dict[str, Any]:
        tss_val = float(rng.normal(380.0, 50.0))
        tds_val = float(rng.normal(2850.0, 200.0))
        return {
            "COD_mg_L": float(rng.normal(5800.0, 500.0)),
            "BOD_mg_L": float(rng.normal(1400.0, 150.0)),
            "pH": float(rng.normal(6.9, 0.2)),
            "TDS_mg_L": tds_val,
            "turbidity_NTU": float(0.85 * tss_val + rng.normal(0, 15.0)),
            "colour_PtCo": float(rng.normal(2600.0, 250.0)),
            "total_solids_mg_L": float(tds_val + tss_val + rng.normal(0, 15.0)),
            "total_suspended_solids_mg_L": tss_val,
            "chloride_mg_L": float(rng.normal(380.0, 30.0)),
            "sulphate_mg_L": float(rng.normal(450.0, 40.0)),
        }

    # Scenario 1: Suspiciously Low COD (Dilution / Sensor Washing Tampering)
    for _ in range(scenario_counts["low_cod"]):
        atk_counter += 1
        curr_time += timedelta(minutes=10)
        rec = make_base_effluent(curr_time)
        # COD dropped to tap water levels while other parameters remain industrial
        rec["COD_mg_L"] = round(float(rng.uniform(15.0, 75.0)), 2)
        rec["BOD_mg_L"] = round(float(rng.uniform(5.0, 20.0)), 2)
        attack_records.append({
            "sample_id": f"SYNTH_ATK_{atk_counter:05d}",
            "timestamp": curr_time.isoformat(),
            **{k: round(v, 2) if isinstance(v, float) else v for k, v in rec.items()},
            "is_anomaly": 1,
            "label": "anomaly",
            "attack_type": "low_cod",
            "data_provenance": "SYNTHETIC",
            "is_synthetic": True,
        })

    # Scenario 2: Extremely High COD (Acute Chemical Dumping / Spent Dye Slug)
    for _ in range(scenario_counts["high_cod"]):
        atk_counter += 1
        curr_time += timedelta(minutes=10)
        rec = make_base_effluent(curr_time)
        # Massive COD surge 25,000 - 52,000 mg/L
        rec["COD_mg_L"] = round(float(rng.uniform(24000.0, 52000.0)), 2)
        rec["BOD_mg_L"] = round(float(rec["COD_mg_L"] * 0.32), 2)
        rec["colour_PtCo"] = round(float(rng.uniform(8500.0, 18000.0)), 2)
        attack_records.append({
            "sample_id": f"SYNTH_ATK_{atk_counter:05d}",
            "timestamp": curr_time.isoformat(),
            **{k: round(v, 2) if isinstance(v, float) else v for k, v in rec.items()},
            "is_anomaly": 1,
            "label": "anomaly",
            "attack_type": "high_cod",
            "data_provenance": "SYNTHETIC",
            "is_synthetic": True,
        })

    # Scenario 3: Unusual COD & Turbidity Decoupling (Physical Relationship Severed)
    for sub_i in range(scenario_counts["cod_turbidity_decoupling"]):
        atk_counter += 1
        curr_time += timedelta(minutes=10)
        rec = make_base_effluent(curr_time)
        if sub_i % 2 == 0:
            # Extreme COD but pristine optical turbidity
            rec["COD_mg_L"] = round(float(rng.uniform(18000.0, 26000.0)), 2)
            rec["turbidity_NTU"] = round(float(rng.uniform(8.0, 25.0)), 2)
            rec["total_suspended_solids_mg_L"] = round(float(rng.uniform(15.0, 30.0)), 2)
        else:
            # Low COD but high optical turbidity
            rec["COD_mg_L"] = round(float(rng.uniform(60.0, 180.0)), 2)
            rec["turbidity_NTU"] = round(float(rng.uniform(750.0, 950.0)), 2)
            rec["total_suspended_solids_mg_L"] = round(float(rng.uniform(700.0, 900.0)), 2)
        attack_records.append({
            "sample_id": f"SYNTH_ATK_{atk_counter:05d}",
            "timestamp": curr_time.isoformat(),
            **{k: round(v, 2) if isinstance(v, float) else v for k, v in rec.items()},
            "is_anomaly": 1,
            "label": "anomaly",
            "attack_type": "cod_turbidity_decoupling",
            "data_provenance": "SYNTHETIC",
            "is_synthetic": True,
        })

    # Scenario 4: Sensor Flatlining (Sensor stuck reporting identical constant value)
    flatline_cod = 4850.00
    flatline_ph = 7.10
    flatline_turb = 240.00
    for _ in range(scenario_counts["sensor_flatline"]):
        atk_counter += 1
        curr_time += timedelta(minutes=10)
        rec = make_base_effluent(curr_time)
        rec["COD_mg_L"] = flatline_cod
        rec["pH"] = flatline_ph
        rec["turbidity_NTU"] = flatline_turb
        attack_records.append({
            "sample_id": f"SYNTH_ATK_{atk_counter:05d}",
            "timestamp": curr_time.isoformat(),
            **{k: round(v, 2) if isinstance(v, float) else v for k, v in rec.items()},
            "is_anomaly": 1,
            "label": "anomaly",
            "attack_type": "sensor_flatline",
            "data_provenance": "SYNTHETIC",
            "is_synthetic": True,
        })

    # Scenario 5: Sudden Sensor Changes (Impossible instant step change)
    for step_i in range(scenario_counts["sudden_spike"]):
        atk_counter += 1
        curr_time += timedelta(minutes=10)
        rec = make_base_effluent(curr_time)
        # Alternating massive 7x spike and instant drop
        if step_i % 2 == 0:
            rec["COD_mg_L"] = round(float(rec["COD_mg_L"] * 5.5), 2)
            rec["pH"] = round(float(min(12.5, rec["pH"] + 4.5)), 2)
        else:
            rec["COD_mg_L"] = round(float(rec["COD_mg_L"] * 0.05), 2)
            rec["pH"] = round(float(max(2.0, rec["pH"] - 4.5)), 2)
        attack_records.append({
            "sample_id": f"SYNTH_ATK_{atk_counter:05d}",
            "timestamp": curr_time.isoformat(),
            **{k: round(v, 2) if isinstance(v, float) else v for k, v in rec.items()},
            "is_anomaly": 1,
            "label": "anomaly",
            "attack_type": "sudden_spike",
            "data_provenance": "SYNTHETIC",
            "is_synthetic": True,
        })

    # Scenario 6: Gradual Sensor Drift (Monotonic bias ramp)
    n_drift = scenario_counts["gradual_drift"]
    for drift_step in range(n_drift):
        atk_counter += 1
        curr_time += timedelta(minutes=10)
        rec = make_base_effluent(curr_time)
        # Shift COD downwards progressively by 130 mg/L per interval
        drift_delta = (drift_step + 1) * 130.0
        rec["COD_mg_L"] = round(max(10.0, float(rec["COD_mg_L"] - drift_delta)), 2)
        rec["pH"] = round(min(11.5, float(rec["pH"] + drift_step * 0.12)), 2)
        attack_records.append({
            "sample_id": f"SYNTH_ATK_{atk_counter:05d}",
            "timestamp": curr_time.isoformat(),
            **{k: round(v, 2) if isinstance(v, float) else v for k, v in rec.items()},
            "is_anomaly": 1,
            "label": "anomaly",
            "attack_type": "gradual_drift",
            "data_provenance": "SYNTHETIC",
            "is_synthetic": True,
        })

    df_attack = pd.DataFrame(attack_records)

    logger.info(
        f"Generated synthetic demonstration dataset: "
        f"{len(df_normal)} normal observations, {len(df_attack)} attack observations."
    )
    return df_normal, df_attack


def generate_and_save_demo_datasets(
    output_dir: Union[str, Path] = "data/synthetic_demo",
    n_normal: int = 1000,
    n_attack: int = 200,
    random_seed: int = 42,
) -> Tuple[Path, Path]:
    """
    Generate synthetic normal and attack datasets and persist them to data/synthetic_demo/.
    Never writes into or modifies data/raw/.

    Returns:
        Tuple of (Path to normal_demo.csv, Path to attack_demo.csv)
    """
    out_path = Path(output_dir)
    out_path.mkdir(parents=True, exist_ok=True)

    df_norm, df_atk = generate_synthetic_dataset(
        n_normal=n_normal,
        n_attack=n_attack,
        random_seed=random_seed,
    )

    norm_file = out_path / "normal_demo.csv"
    atk_file = out_path / "attack_demo.csv"

    df_norm.to_csv(norm_file, index=False)
    df_atk.to_csv(atk_file, index=False)

    logger.info(f"Saved synthetic normal demo dataset to: {norm_file.resolve()}")
    logger.info(f"Saved synthetic attack demo dataset to: {atk_file.resolve()}")

    return norm_file, atk_file


def train_demo_model(
    config_path: Union[str, Path] = "config/data_config.yaml",
    demo_data_dir: Union[str, Path] = "data/synthetic_demo",
    demo_models_dir: Union[str, Path] = "models/demo",
    random_seed: int = 42,
) -> Dict[str, Any]:
    """
    Train Isolation Forest specifically for the synthetic demonstration mode.
    Guarantees:
      1. Trains strictly on normal synthetic observations (normal_demo.csv).
      2. Zero attack records enter the training subset.
      2a. The latest DEMO_TEST_RATIO of normal records are held out for evaluation only.
      3. Saves artifacts strictly into models/demo/ without overwriting production models.
      4. Stamped with model_mode='SYNTHETIC_DEMO' and data_provenance='SYNTHETIC'.
    """
    data_dir = Path(demo_data_dir)
    models_dir = Path(demo_models_dir)
    models_dir.mkdir(parents=True, exist_ok=True)

    norm_csv = data_dir / "normal_demo.csv"
    atk_csv = data_dir / "attack_demo.csv"

    if not norm_csv.exists() or not atk_csv.exists():
        logger.info("Demo datasets not found. Generating them first...")
        generate_and_save_demo_datasets(output_dir=data_dir, random_seed=random_seed)

    # Load configuration
    cfg = load_config(config_path)

    # Configure strictly for synthetic demo
    cfg["dataset"]["raw_data_path"] = str(norm_csv)
    cfg["dataset"]["validation_data_path"] = None
    cfg["artifacts"]["models_dir"] = str(models_dir)
    cfg["artifacts"]["model_filename"] = "isolation_forest_demo.joblib"
    cfg["artifacts"]["preprocessor_filename"] = "preprocessor_demo.joblib"
    cfg["artifacts"]["metadata_filename"] = "model_metadata.json"
    cfg["splitting"]["strategy"] = "chronological"
    cfg["splitting"]["timestamp_column"] = "timestamp"
    cfg["splitting"]["train_ratio"] = 0.80
    cfg["splitting"]["test_ratio"] = DEMO_TEST_RATIO

    # Ensure required features are present
    cfg["features"]["numerical"] = SIMULATION_FEATURES
    cfg["features"]["categorical"] = []

    logger.info(f"Training synthetic demonstration model on: {norm_csv}")
    manifest = run_training(cfg)

    # Augment manifest with explicit demo mode stamps
    meta_path = models_dir / "model_metadata.json"
    with open(meta_path, "r", encoding="utf-8") as f:
        meta = json.load(f)

    meta["model_mode"] = "SYNTHETIC_DEMO"
    meta["data_provenance"] = "SYNTHETIC"
    meta["model_version"] = "iforest-demo-v1.0"
    meta["synthetic_disclaimer"] = (
        "Demonstration model trained on synthetic wastewater simulation data. "
        "Does not establish real-world industrial accuracy or validate detection "
        "performance on actual factory telemetry."
    )

    with open(meta_path, "w", encoding="utf-8") as f:
        json.dump(meta, f, indent=2)

    logger.info(f"Synthetic demo training completed. Artifacts saved in: {models_dir}")
    return meta


def evaluate_demo_model(
    demo_models_dir: Union[str, Path] = "models/demo",
    demo_data_dir: Union[str, Path] = "data/synthetic_demo",
    config_path: Union[str, Path] = "config/data_config.yaml",
) -> Dict[str, Any]:
    """
    Evaluate the trained synthetic demonstration model against the held-out normal test
    observations (never seen during fitting or threshold calibration) and all injected
    attack scenarios. Reports combined (Isolation Forest + physical rules) metrics,
    Isolation-Forest-only metrics, and a per-attack-scenario breakdown.
    """
    models_dir = Path(demo_models_dir)
    data_dir = Path(demo_data_dir)

    df_norm = data_loader.load_dataset(data_dir / "normal_demo.csv")
    df_atk = data_loader.load_dataset(data_dir / "attack_demo.csv")

    with open(models_dir / "model_metadata.json", "r", encoding="utf-8") as f:
        meta = json.load(f)
    holdout_ratio = float(meta.get("holdout_test", {}).get("test_ratio", 0.0))
    if holdout_ratio <= 0.0:
        raise ValueError(
            "Demo model was trained without a held-out test split, so no unbiased normal test "
            "set exists. Retrain with: python -m src.synthetic_data_generator --train"
        )

    # Reconstruct the exact held-out subset with the same split used at training time
    cfg = load_config(config_path)
    cfg["splitting"]["strategy"] = meta.get("split_strategy", "chronological")
    cfg["splitting"]["timestamp_column"] = "timestamp"
    cfg["splitting"]["test_ratio"] = holdout_ratio
    _, df_test_norm = split_holdout_test(df_norm, cfg)

    # Each scenario is scored as its own sensor stream. In one continuous stream, sequential
    # detectors (rolling windows, CUSUM) carry state from one scenario into the next: a large
    # low_cod shift would keep CUSUM alarming through every later scenario.
    df_test_norm = df_test_norm.assign(sensorId="DEMO-normal")
    df_atk = df_atk.assign(sensorId="DEMO-" + df_atk["attack_type"].astype(str))
    df_test_combined = pd.concat([df_test_norm, df_atk], ignore_index=True)
    cfg["artifacts"]["model_filename"] = "isolation_forest_demo.joblib"
    cfg["artifacts"]["preprocessor_filename"] = "preprocessor_demo.joblib"
    cfg["features"]["numerical"] = SIMULATION_FEATURES
    cfg["features"]["categorical"] = []

    eval_results = evaluate_dataset(
        data_path=df_test_combined,
        config_path=cfg,
        models_dir=str(models_dir),
        label_column="is_anomaly",
        group_column="attack_type",
    )

    report = {
        "model_mode": "SYNTHETIC_DEMO",
        "data_provenance": "SYNTHETIC",
        "total_test_samples": len(df_test_combined),
        "normal_test_samples": len(df_test_norm),
        "normal_test_source": "held-out (not used for fitting or threshold calibration)",
        "attack_test_samples": len(df_atk),
        "metrics": eval_results.get("supervised_metrics", {}),
        "isolation_forest_only_metrics": eval_results.get("isolation_forest_only_metrics", {}),
        "consistency_rules_only_metrics": eval_results.get("consistency_rules_only_metrics", {}),
        "cusum_only_metrics": eval_results.get("cusum_only_metrics", {}),
        "per_scenario": eval_results.get("per_group_breakdown", {}),
        "score_distribution": eval_results.get("score_distribution", {}),
        "disclaimer": (
            "Metrics reflect synthetic demonstration performance only and "
            "do not represent authentic industrial wastewater accuracy. The physical "
            "rules check relationships the generator itself encodes, so high synthetic "
            "recall is expected and does not transfer automatically to real telemetry."
        ),
    }

    logger.info("Synthetic Demo Evaluation Report:")
    logger.info(json.dumps(report, indent=2))
    return report


