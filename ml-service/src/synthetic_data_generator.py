"""
EnviroTrust ML Service — Synthetic Demonstration Data Generator & Demo Pipeline

DISCLAIMER & RESEARCH INTEGRITY:
--------------------------------
This module generates synthetic environmental simulation data solely for
architectural demonstration and hackathon verification of the EnviroTrust
sensor-tampering and anomaly-detection pipeline.

None of the records generated by this module are authentic industrial measurements.
Every generated observation is unambiguously stamped with:
    data_provenance = "SYNTHETIC"
    is_synthetic = True

Authentic research datasets (stored in data/raw/) are strictly isolated and never
modified or supplemented with mock values.

SIMULATION ASSUMPTIONS & PHYSICAL RELATIONSHIPS:
-----------------------------------------------
1. Mass Conservation (Solids):
   Total Solids (TS) is strictly modelled as Total Dissolved Solids (TDS) +
   Total Suspended Solids (TSS) plus minor analytical gravimetric measurement noise.
   total_solids_mg_L ~= TDS_mg_L + total_suspended_solids_mg_L.

2. Biodegradability Ratio (COD & BOD):
   In textile/dye industrial effluent, recalcitrant chromophores yield a typical
   BOD/COD ratio of 0.20 to 0.35. BOD is physically coupled to COD:
   BOD_mg_L = COD_mg_L * (0.24 + noise).

3. Particulate Light Scattering (TSS & Turbidity):
   Suspended particulate matter scatters light directly. Turbidity is positively
   correlated with TSS: turbidity_NTU = 0.85 * TSS + optical_noise.

4. Optical Colour & Organics:
   Dye chromophore concentration correlates with COD and turbidity:
   colour_PtCo = 0.4 * COD + 2.0 * turbidity + color_noise.

5. Ionic Dissolved Constituents:
   Chloride and Sulphate are modeled as bounded ionic fractions of TDS:
   chloride_mg_L + sulphate_mg_L < TDS_mg_L.

6. Temporal Dynamics:
   Observations are generated chronologically at 10-minute intervals with
   a subtle diurnal batch-production rhythm: sin(2 * pi * hour / 24).
"""

from datetime import datetime, timedelta, timezone
import json
import logging
from pathlib import Path
from typing import Any, Dict, List, Optional, Tuple, Union
import numpy as np
import pandas as pd

import data_loader
from data_loader import load_config
